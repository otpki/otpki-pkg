package main

import (
	"fmt"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"text/template"

	"github.com/otpki/otpki-pkg/tools/sqlc"
)

var debugLogging = os.Getenv("SQLC_DEBUG") == "true"

func main() {
	if len(os.Args) < 4 {
		log.Fatal("Usage: go run generate_model_to_insert.go <directory> <output_package> <output_file>")
	}

	directory := os.Args[1]
	outputPackage := os.Args[2]
	outputFile := os.Args[3]

	// Get list of ignored queries from SQL files
	// Look in the queries directory, not the db directory
	queriesDir := filepath.Join(filepath.Dir(directory), "queries")
	ignoredQueries := sqlc.GetIgnoredQueries(queriesDir)

	// Find all go files in the directory
	var goFiles []string
	err := filepath.Walk(directory, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(path, ".go") {
			goFiles = append(goFiles, path)
		}
		return nil
	})
	if err != nil {
		log.Fatalf("Failed to walk directory: %v", err)
	}
	slices.Sort(goFiles)

	if len(goFiles) == 0 {
		if debugLogging {
			log.Printf("No .go files found in directory: %s", directory)
		}
		os.Exit(0)
	}

	// Parse all structs from all files
	allModelStructs := make(map[string][]sqlc.Field)  // struct name: Fields
	allInsertStructs := make(map[string][]sqlc.Field) // struct name: Fields

	for _, file := range goFiles {
		structs, err := sqlc.ParseStructs(file)
		if err != nil {
			log.Printf("Warning: Failed to parse %s: %v", file, err)
			continue
		}

		// Categorize structs into insert param structs and model structs
		for structName, structFields := range structs {
			if strings.Contains(structName, "Insert") && strings.Contains(structName, "Params") {
				allInsertStructs[structName] = structFields
			} else if !strings.Contains(structName, "Params") && !strings.Contains(structName, "Result") && !strings.Contains(structName, "Quer") {
				// Everything else is a model struct (minus params, queriers and results)
				allModelStructs[structName] = structFields
			}
		}
	}

	if len(allModelStructs) == 0 {
		if debugLogging {
			log.Printf("No model structs found in directory: %s", directory)
		}
		os.Exit(0)
	}

	if len(allInsertStructs) == 0 {
		if debugLogging {
			log.Printf("No insert params structs found in directory: %s", directory)
		}
		os.Exit(0)
	}
	if debugLogging {
		log.Printf("Found %d model structs and %d insert params structs", len(allModelStructs), len(allInsertStructs))
	}

	// Generate conversions for all matching model-insert pairs
	var allResults []sqlc.ConversionResult
	modelNames := slices.Collect(maps.Keys(allModelStructs))
	slices.Sort(modelNames)
	reg := sqlc.NewMappingRegistry(modelNames)
	insertStructNames := slices.Collect(maps.Keys(allInsertStructs))
	slices.Sort(insertStructNames)

	for _, insertStructName := range insertStructNames {
		insertStructFields := allInsertStructs[insertStructName]
		// Check if this insert struct should be ignored
		if ignoredQueries[insertStructName] {
			if debugLogging {
				log.Printf("Skipping ignored insert struct: %s", insertStructName)
			}
			continue
		}

		modelName, _ := reg.FindBestMatch(insertStructName)

		// If we found a matching model for the insert param, generate the params for the code generation
		if modelName != "" {
			// Check if this model-to-insert mapping should be ignored
			if sqlc.ShouldIgnoreMapping(ignoredQueries, modelName, insertStructName) {
				if debugLogging {
					log.Printf("Skipping ignored mapping: %s -> %s", modelName, insertStructName)
				}
				continue
			}

			result := generateInsertConversion(modelName, allModelStructs[modelName], insertStructName, insertStructFields)

			// Only generate if conversion is actually needed
			if result.NeedsConversion {
				if debugLogging {
					log.Printf("Generating conversion for %s -> %s", modelName, insertStructName)
				}
				allResults = append(allResults, result)
			} else {
				if debugLogging {
					log.Printf("Skipping conversion for %s -> %s (no conversion needed)", modelName, insertStructName)
				}
			}
		}
	}

	if len(allResults) == 0 {
		if debugLogging {
			log.Println("No matching model-insert pairs found")
		}
		os.Exit(0)
	}

	// Generate the Go code for all conversions
	var buf strings.Builder
	buf.WriteString("// Code generated by generate_model_to_insert.go. DO NOT EDIT.\n\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", outputPackage))

	// Convert results to interface slice for common function
	var results []any
	for _, result := range allResults {
		results = append(results, result)
	}

	// Generate imports using common function
	needsPgxType := sqlc.CheckIfNeedsPgxImport(results)
	needsUUID := sqlc.CheckIfNeedsUUIDImport(results)
	sqlc.GenerateImportSection(&buf, needsPgxType, needsUUID, false)

	for i, result := range allResults {
		if i > 0 {
			buf.WriteString("\n")
		}
		err = generateConversionCode(&buf, result)
		if err != nil {
			log.Fatalf("Failed to generate conversion for %s: %v", result.ModelStructName, err)
		}
	}

	// Write to a file
	err = os.WriteFile(outputFile, []byte(buf.String()), 0644)
	if err != nil {
		log.Fatalf("Failed to write output file: %v", err)
	}

	if debugLogging {
		log.Printf("Generated %d insert conversions.", len(allResults))
	}
}

func generateInsertConversion(modelName string, modelFields []sqlc.Field, insertStructName string, insertStructFields []sqlc.Field) sqlc.ConversionResult {
	// Generate field mappings (don't skip ID for inserts since they might need it)
	fieldMappings := sqlc.GenerateFieldMappings(modelFields, insertStructFields, false)

	// For inserts, be more lenient - if there are any field mappings at all, we need the function
	// This is because inserts often need simple type conversions or field assignments
	needsConversion := len(fieldMappings) > 0

	return sqlc.ConversionResult{
		ModelStructName:    modelName,
		ParamsStructName:   insertStructName,
		ModelStructFields:  modelFields,
		ParamsStructFields: insertStructFields,
		FieldMappings:      fieldMappings,
		NeedsConversion:    needsConversion,
	}
}

func generateConversionCode(buf *strings.Builder, result sqlc.ConversionResult) error {
	tmpl := template.Must(template.New("conversion").Parse(`
// {{.ModelStructName}}ToInsertParams converts {{.ModelStructName}} model to insert parameters
func {{.ModelStructName}}ToInsertParams(model *{{.ModelStructName}}) {{.ParamsStructName}} {
	if model == nil {
		return {{.ParamsStructName}}{}
	}
	
	return {{.ParamsStructName}}{ {{range .FieldMappings}}
		{{.ParamsField}}: {{.Conversion}},{{end}}
	}
}`))

	return tmpl.Execute(buf, result)
}
