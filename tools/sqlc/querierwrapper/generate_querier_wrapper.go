package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/samber/oops"
)

var debugLogging = os.Getenv("SQLC_DEBUG") == "true"

type dbtxCapabilities struct {
	CopyFrom  bool
	SendBatch bool
}

func main() {
	if len(os.Args) < 3 {
		log.Fatal("Usage: go run generate_querier_wrapper.go <package_name> <output_file>")
	}

	packageName := os.Args[1]
	outputPath := os.Args[2]

	caps, err := detectDBTXCapabilities(outputPath)
	if err != nil {
		log.Printf("Warning: failed to inspect generated DBTX interface: %v", err)
	}

	// Generate the querier wrapper content.
	content := fmt.Sprintf(`// Code generated by generate_querier_wrapper.go. DO NOT EDIT.
package %s

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

type txContextKey struct{}

// ContextWithTx returns a child context that carries tx.
// Any sqlc query executed with the returned context will use tx instead of the
// fallback DBTX that was passed to NewQuerierWithTx.
func ContextWithTx(ctx context.Context, tx pgx.Tx) context.Context {
	if tx == nil {
		return ctx
	}
	return context.WithValue(ctx, txContextKey{}, tx)
}

// TxFromContext returns the transaction carried by ctx, if any.
func TxFromContext(ctx context.Context) (pgx.Tx, bool) {
	tx, ok := ctx.Value(txContextKey{}).(pgx.Tx)
	return tx, ok && tx != nil
}

type contextTxDBTX struct {
	fallback DBTX
}

func (db *contextTxDBTX) dbtx(ctx context.Context) DBTX {
	if tx, ok := TxFromContext(ctx); ok {
		return tx
	}
	return db.fallback
}

func (db *contextTxDBTX) Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error) {
	return db.dbtx(ctx).Exec(ctx, sql, args...)
}

func (db *contextTxDBTX) Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error) {
	return db.dbtx(ctx).Query(ctx, sql, args...)
}

func (db *contextTxDBTX) QueryRow(ctx context.Context, sql string, args ...any) pgx.Row {
	return db.dbtx(ctx).QueryRow(ctx, sql, args...)
}
%s%s
type QuerierWithTx interface {
	Querier
	WithTransaction(tx pgx.Tx) QuerierWithTx
}

func NewQuerierWithTx(db DBTX) QuerierWithTx {
	return New(&contextTxDBTX{fallback: db})
}

func (q *Queries) WithTransaction(tx pgx.Tx) QuerierWithTx {
	return q.WithTx(tx)
}
`, packageName, copyFromMethod(caps), sendBatchMethod(caps))

	if err := writeToFile(outputPath, content); err != nil {
		fmt.Println("Error:", err)
		return
	}

	if debugLogging {
		log.Printf("Generated querier wrapper: %s", outputPath)
	}
}

func copyFromMethod(caps dbtxCapabilities) string {
	if !caps.CopyFrom {
		return ""
	}
	return `
func (db *contextTxDBTX) CopyFrom(ctx context.Context, tableName pgx.Identifier, columnNames []string, rowSrc pgx.CopyFromSource) (int64, error) {
	return db.dbtx(ctx).CopyFrom(ctx, tableName, columnNames, rowSrc)
}
`
}

func sendBatchMethod(caps dbtxCapabilities) string {
	if !caps.SendBatch {
		return ""
	}
	return `
func (db *contextTxDBTX) SendBatch(ctx context.Context, batch *pgx.Batch) pgx.BatchResults {
	return db.dbtx(ctx).SendBatch(ctx, batch)
}
`
}

func detectDBTXCapabilities(outputPath string) (dbtxCapabilities, error) {
	var caps dbtxCapabilities

	outputAbs, err := filepath.Abs(outputPath)
	if err != nil {
		return caps, err
	}

	dir := filepath.Dir(outputAbs)
	entries, err := os.ReadDir(dir)
	if err != nil {
		// On a first generation run the output directory may not exist yet. In that
		// case, generate the standard wrapper and let sqlc's normal DBTX check fail
		// only if it truly needs extra methods.
		if os.IsNotExist(err) {
			return caps, nil
		}
		return caps, err
	}

	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}

		path := filepath.Join(dir, entry.Name())
		pathAbs, err := filepath.Abs(path)
		if err != nil {
			return caps, err
		}
		if pathAbs == outputAbs {
			continue
		}

		node, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return caps, err
		}

		ast.Inspect(node, func(n ast.Node) bool {
			typeSpec, ok := n.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != "DBTX" {
				return true
			}

			iface, ok := typeSpec.Type.(*ast.InterfaceType)
			if !ok {
				return false
			}

			for _, field := range iface.Methods.List {
				for _, name := range field.Names {
					switch name.Name {
					case "CopyFrom":
						caps.CopyFrom = true
					case "SendBatch":
						caps.SendBatch = true
					}
				}
			}

			return false
		})
	}

	return caps, nil
}

func writeToFile(targetPath string, content string) error {
	dir := filepath.Dir(targetPath)

	if err := os.MkdirAll(dir, 0755); err != nil {
		return oops.Errorf("failed to create directory: %w", err)
	}

	if err := os.WriteFile(targetPath, []byte(content), 0644); err != nil {
		return oops.Errorf("failed to write file: %w", err)
	}

	return nil
}
