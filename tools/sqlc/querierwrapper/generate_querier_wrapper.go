package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
)

var debugLogging = os.Getenv("SQLC_DEBUG") == "true"

func main() {
	if len(os.Args) < 3 {
		log.Fatal("Usage: go run generate_querier_wrapper.go <package_name> <output_file>")
	}

	outputPath := os.Args[2]
	packageName := os.Args[1]

	// Generate the querier wrapper content
	content := fmt.Sprintf(`// Code generated by generate_model_to_update.go. DO NOT EDIT.
package %s

import "github.com/jackc/pgx/v5"

type QuerierWithTx interface {
	Querier
	WithTransaction(tx pgx.Tx) QuerierWithTx
}

func NewQuerierWithTx(db DBTX) QuerierWithTx {
	return New(db)
}

func (q *Queries) WithTransaction(tx pgx.Tx) QuerierWithTx {
	return q.WithTx(tx)
}
`, packageName)

	err := writeToFile(outputPath, content)
	if err != nil {
		fmt.Println("Error:", err)
		return
	}

	if debugLogging {
		log.Printf("Generated querier wrapper: %s", outputPath)
	}
}

func writeToFile(targetPath string, content string) error {
	dir := filepath.Dir(targetPath)

	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("failed to create directory: %w", err)
	}

	if err := os.WriteFile(targetPath, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write file: %w", err)
	}

	return nil
}
