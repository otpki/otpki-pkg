package main

import (
	"fmt"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"text/template"

	"github.com/otpki/otpki-pkg/tools/sqlc"
)

var debugLogging = os.Getenv("SQLC_DEBUG") == "true"

func main() {
	if len(os.Args) < 4 {
		log.Fatal("Usage: go run generate_model_to_update.go <directory> <output_package> <output_file>")
	}

	directory := os.Args[1]
	outputPackage := os.Args[2]
	outputFile := os.Args[3]

	// Get list of ignored queries from SQL files
	// Look in the queries directory, not the db directory
	queriesDir := filepath.Join(filepath.Dir(directory), "queries")
	ignoredQueries := sqlc.GetIgnoredQueries(queriesDir)

	// find all go files in the directory
	var goFiles []string
	err := filepath.Walk(directory, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(path, ".go") {
			goFiles = append(goFiles, path)
		}
		return nil
	})
	if err != nil {
		log.Fatalf("Failed to walk directory: %v", err)
	}
	sort.Strings(goFiles)

	if len(goFiles) == 0 {
		if debugLogging {
			log.Printf("No .go files found in directory: %s", directory)
		}
		os.Exit(0)
	}

	// parse all structs from all files
	allModelStructs := make(map[string][]sqlc.Field)  // struct name: Fields
	allUpdateStructs := make(map[string][]sqlc.Field) // struct name: Fields

	for _, file := range goFiles {
		structs, err := sqlc.ParseStructs(file)
		if err != nil {
			log.Printf("Warning: Failed to parse %s: %v", file, err)
			continue
		}

		// categorize structs into update param structs and model structs
		for structName, structFields := range structs {
			if strings.Contains(structName, "Update") && strings.Contains(structName, "Params") {
				allUpdateStructs[structName] = structFields
			} else if !strings.Contains(structName, "Params") && !strings.Contains(structName, "Result") && !strings.Contains(structName, "Quer") {
				// everything else is a model struct (minus params, queriers and results)
				allModelStructs[structName] = structFields
			}
		}
	}

	if len(allModelStructs) == 0 {
		if debugLogging {
			log.Printf("No model structs found in directory: %s", directory)
		}
		os.Exit(0)
	}

	if len(allUpdateStructs) == 0 {
		if debugLogging {
			log.Printf("No update params structs found in directory: %s", directory)
		}
		os.Exit(0)
	}
	if debugLogging {
		log.Printf("Found %d model structs and %d update params structs", len(allModelStructs), len(allUpdateStructs))
	}

	// generate conversions for all matching model-update pairs
	var allResults []sqlc.UpdateConversionResult
	modelNames := slices.Collect(maps.Keys(allModelStructs))
	sort.Strings(modelNames)
	reg := sqlc.NewMappingRegistry(modelNames)
	updateStructNames := slices.Collect(maps.Keys(allUpdateStructs))
	sort.Strings(updateStructNames)

	for _, updateStructName := range updateStructNames {
		updateStructFields := allUpdateStructs[updateStructName]
		// Check if this update struct should be ignored
		if ignoredQueries[updateStructName] {
			if debugLogging {
				log.Printf("Skipping ignored update struct: %s", updateStructName)
			}
			continue
		}

		modelName, _ := reg.FindBestMatch(updateStructName)

		// if we found a matching model for the update param, generate the params for the code generation
		if modelName != "" {
			// Check if this model-to-update mapping should be ignored
			if sqlc.ShouldIgnoreMapping(ignoredQueries, modelName, updateStructName) {
				if debugLogging {
					log.Printf("Skipping ignored mapping: %s -> %s", modelName, updateStructName)
				}
				continue
			}

			result := generateUpdateConversion(modelName, allModelStructs[modelName], updateStructName, updateStructFields)

			// Only generate if conversion is actually needed
			if result.NeedsConversion {
				if debugLogging {
					log.Printf("Generating conversion for %s -> %s", modelName, updateStructName)
				}
				allResults = append(allResults, result)
			} else {
				if debugLogging {
					log.Printf("Skipping conversion for %s -> %s (no conversion needed)", modelName, updateStructName)
				}
			}
		}
	}

	if len(allResults) == 0 {
		if debugLogging {
			log.Println("No matching model-update pairs found")
		}
		os.Exit(0)
	}

	// generate the Go code for all conversions
	var buf strings.Builder
	buf.WriteString("// Code generated by generate_model_to_update.go. DO NOT EDIT.\n\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", outputPackage))

	// Convert results to interface slice for common function
	var results []any
	for _, result := range allResults {
		results = append(results, result)
	}

	// Generate imports using common function
	needsPgxType := sqlc.CheckIfNeedsPgxImport(results)
	needsUUID := sqlc.CheckIfNeedsUUIDImport(results)
	sqlc.GenerateImportSection(&buf, needsPgxType, needsUUID, true)

	for i, result := range allResults {
		if i > 0 {
			buf.WriteString("\n")
		}
		err = generateConversionCode(&buf, result)
		if err != nil {
			log.Fatalf("Failed to generate conversion for %s: %v", result.ModelStructName, err)
		}
	}

	// write to a file
	err = os.WriteFile(outputFile, []byte(buf.String()), 0644)
	if err != nil {
		log.Fatalf("Failed to write output file: %v", err)
	}

	if debugLogging {
		log.Printf("Generated %d update conversions.", len(allResults))
	}
}

func generateUpdateConversion(modelName string, modelFields []sqlc.Field, updateStructName string, updateStructFields []sqlc.Field) sqlc.UpdateConversionResult {
	// Generate field mappings (skip ID since it's handled separately)
	fieldMappings := sqlc.GenerateFieldMappings(modelFields, updateStructFields, true)

	// Check if any field actually needs conversion
	needsConversion := false
	for _, mapping := range fieldMappings {
		modelField := sqlc.Field{Name: mapping.ModelField, Type: mapping.ModelType}
		updateField := sqlc.Field{Name: mapping.ParamsField, Type: mapping.ParamsType}

		if sqlc.CheckIfFieldNeedsConversion(modelField, updateField, mapping.Conversion) {
			needsConversion = true
			break
		}
	}

	// Check if update struct has FieldMask field
	hasFieldMask := sqlc.CheckIfStructHasField(updateStructFields, "FieldMask")
	if hasFieldMask {
		needsConversion = true // FieldMask processing means we need the function
	}

	// Check if both structs have ID field
	hasID := sqlc.CheckIfBothStructsHaveID(modelFields, updateStructFields)

	return sqlc.UpdateConversionResult{
		ModelStructName:    modelName,
		UpdateStructName:   updateStructName,
		ModelStructFields:  modelFields,
		UpdateStructFields: updateStructFields,
		FieldMappings:      fieldMappings,
		HasFieldMask:       hasFieldMask,
		NeedsConversion:    needsConversion,
		HasID:              hasID,
	}
}

func generateUpdateFieldConversion(modelField, updateField sqlc.Field) string {
	return sqlc.GenerateFieldConversion(modelField, updateField)
}

func generateConversionCode(buf *strings.Builder, result sqlc.UpdateConversionResult) error {
	tmpl := template.Must(template.New("conversion").Parse(`
// {{.ModelStructName}}ToUpdateParams converts {{.ModelStructName}} model and field mask to update parameters
// Optional submask parameter can be provided to handle nested field masks
func {{.ModelStructName}}ToUpdateParams(model *{{.ModelStructName}}, mask *fieldmaskpb.FieldMask, submask ...string) {{.UpdateStructName}} {
	if model == nil {
		return {{.UpdateStructName}}{}
	}
	{{if .HasFieldMask}}
	// Build field mask JSON based on user-provided mask
	var fieldMaskPaths []string
	
	if mask != nil {
		mask = proto.Clone(mask).(*fieldmaskpb.FieldMask)
		mask.Normalize()

		if len(submask) > 0 {
			// Apply submask filtering
			var filteredPaths []string
			submaskPrefix := submask[0] + "."
			for _, path := range mask.Paths {
				if strings.HasPrefix(path, submaskPrefix) {
					filteredPaths = append(filteredPaths, strings.TrimPrefix(path, submaskPrefix))
				}
			}
			mask.Paths = filteredPaths
		}
		
		// Convert user-provided mask paths to DB field names
		for _, path := range mask.Paths {
			fieldMaskPaths = append(fieldMaskPaths, path)
		}
	} else {
		// No mask provided - include all fields
		fieldMaskPaths = []string{ {{range .FieldMappings}}
			"{{.JSONName}}",{{end}}
		}
	}
	
	// Convert field mask paths to JSON
	var fieldMaskJSON []byte
	if len(fieldMaskPaths) > 0 {
    	fieldMaskJSON = []byte("[\"" + strings.Join(fieldMaskPaths, "\",\"") + "\"]")
	} else {
		fieldMaskJSON = []byte("[]")
	}
	{{end}}
	
	params := {{.UpdateStructName}}{
		{{if .HasID}}ID:        model.ID,{{end}}{{if .HasFieldMask}}
		FieldMask: fieldMaskJSON,{{end}}{{range .FieldMappings}}
		{{.ParamsField}}: {{.Conversion}},{{end}}
	}
	
	return params
}`))

	return tmpl.Execute(buf, result)
}
