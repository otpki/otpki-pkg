func main() {
	var flags flag.FlagSet
	pulsePkgFlag := flags.String("pulse_pkg", "github.com/otpki/otpki-pkg/spfy/pulse", "import path for the pulse package")
	rpcPkgFlag := flags.String("rpc_pkg", "github.com/otpki/otpki-pkg/spfy/pulse/rpc", "import path for the pulse rpc package")
	protogen.Options{ParamFunc: flags.Set}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO3
		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_MAX
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
		for _, f := range gen.Files {
			if f.Generate && len(f.Services) > 0 {
				generateFile(gen, f, *pulsePkgFlag, *rpcPkgFlag)
			}
		}
		return nil
	})
}

