func generateFile(gen *protogen.Plugin, file *protogen.File, pulsePkg, rpcPkg string) {
	filename := file.GeneratedFilenamePrefix + ".pulse.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	services := make([]ServiceData, 0, len(file.Services))
	for _, service := range file.Services {
		methods := make([]MethodData, 0, len(service.Methods))
		for _, method := range service.Methods {
			methods = append(methods, MethodData{Name: method.GoName, InputType: method.Input.GoIdent.GoName, OutputType: method.Output.GoIdent.GoName})
		}
		services = append(services, ServiceData{Name: service.GoName, FullName: string(file.Desc.Package()) + "." + string(service.Desc.Name()), ClientName: service.GoName + "PulseClient", HandlerName: service.GoName + "PulseHandler", Methods: methods})
	}
	data := FileData{PackageName: string(file.GoPackageName), PulsePkg: pulsePkg, PulseAlias: importAlias(pulsePkg), RPCPkg: rpcPkg, RPCAlias: importAlias(rpcPkg), Services: services}
	if err := fileTemplate.Execute(g, data); err != nil {
		gen.Error(err)
	}
}

func importAlias(p string) string {
	base := path.Base(p)
	base = strings.ReplaceAll(base, "-", "_")
	if base == "rpc" {
		return "pulserpc"
	}
	return base
}
