package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"log"
	"path/filepath"
	"strings"

	"github.com/otpki/otpki-pkg/tools/authcommon"
	"golang.org/x/tools/go/packages"
)

var (
	rootPath = flag.String("root", "./internal", "root path to search for packages with @auth annotations")
	verbose  = flag.Bool("v", false, "verbose output for debugging")
)

func main() {
	flag.Parse()

	// auth discover all packages with @auth annotations
	pkgsWithAuth, err := authcommon.DiscoverPackagesWithAuth(*rootPath, *verbose)
	if err != nil {
		panic("Error discovering packages with @auth annotations: " + err.Error())
	}

	if len(pkgsWithAuth) == 0 {
		log.Println("No packages with @auth annotations found")
		return
	}

	if *verbose {
		log.Printf("Found %d packages with @auth annotations:\n", len(pkgsWithAuth))
		for _, pkgWithAuth := range pkgsWithAuth {
			log.Printf("  - %s\n", pkgWithAuth.Path)
		}
	}

	// generate auth wrappers for each discovered package
	for _, pkgWithAuth := range pkgsWithAuth {
		err := generateForPackage(pkgWithAuth)
		if err != nil {
			panic("Error generating for pkg: " + pkgWithAuth.Path + ": " + err.Error())
		}
	}
}

// code generation

func generateForPackage(pkgWithAuth authcommon.PackageWithAuth) error {
	if len(pkgWithAuth.Interfaces) == 0 {
		log.Printf("Warning: No interfaces with @auth found in %s\n", pkgWithAuth.Path)
		return nil
	}

	code, err := generate(pkgWithAuth)
	if err != nil {
		return fmt.Errorf("failed to generate code for %s: %w", pkgWithAuth.Path, err)
	}

	// put output in the first directory of the package
	dir := filepath.Dir(pkgWithAuth.Package.CompiledGoFiles[0])
	target := filepath.Join(dir, "authwrap.gen.go")

	return authcommon.WriteGeneratedFile(target, "auth wrapper", code, *verbose)
}

func generate(pkgWithAuth authcommon.PackageWithAuth) ([]byte, error) {
	var b bytes.Buffer

	// header
	fmt.Fprintf(&b, "// Code generated by authwrapgen. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Package: %s\n", pkgWithAuth.Path)
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgWithAuth.Package.Name)

	// imports
	imports := extractImports(pkgWithAuth.Package.Syntax, pkgWithAuth.Interfaces)
	var importList []string
	for alias, path := range imports {
		if alias == path {
			importList = append(importList, fmt.Sprintf(`"%s"`, path))
		} else {
			importList = append(importList, fmt.Sprintf(`%s "%s"`, alias, path))
		}
	}
	fmt.Fprintf(&b, "import (\n")
	for _, imp := range importList {
		fmt.Fprintf(&b, "\t%s\n", imp)
	}
	fmt.Fprintf(&b, ")\n\n")

	// generate wrappers for each interface
	for _, iface := range pkgWithAuth.Interfaces {
		genInterfaceWrapper(pkgWithAuth.Package, &b, iface)
	}

	// gofmt
	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("gofmt failed: %w", err)
	}
	return src, nil
}

func extractImports(files []*ast.File, ifaces []authcommon.InterfaceInfo) map[string]string {
	imports := map[string]string{} // alias -> path

	// Find which files contain the interfaces with @auth annotations
	interfaceFiles := map[string]bool{}
	for _, file := range files {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				// Check if this interface name matches any of our interfaces
				for _, iface := range ifaces {
					if ts.Name.Name == iface.Name {
						interfaceFiles[file.Name.String()] = true
						break
					}
				}
			}
		}
	}

	// First, collect imports from files that contain the interfaces with @auth annotations
	for _, file := range files {
		if interfaceFiles[file.Name.String()] {
			collectImportsFromFile(file, imports)
		}
	}

	// Then collect imports from other files (only for aliases not already set)
	for _, file := range files {
		if !interfaceFiles[file.Name.String()] {
			collectImportsFromFile(file, imports)
		}
	}

	// now filter to only keep imports that are actually used in interface methods
	usedImports := map[string]string{}

	// always add required auth packages
	usedImports["authz"] = "github.com/otpki/otpki/pkg/sdk/auth"
	usedImports["auth"] = "github.com/otpki/otpki-protobuf/gen/otpki/common/auth/v1"
	usedImports["context"] = "context"
	usedImports["uuid"] = "github.com/google/uuid"
	usedImports["attribute"] = "go.opentelemetry.io/otel/attribute"
	usedImports["trace"] = "go.opentelemetry.io/otel/trace"
	usedImports["otel"] = "go.opentelemetry.io/otel"
	usedImports["config"] = "github.com/otpki/otpki-pkg/config"

	// extract types used in the provided interfaces
	for _, iface := range ifaces {
		for _, m := range iface.Methods {
			// check params and results for used types
			var allFields []*ast.Field
			allFields = append(allFields, m.Params...)
			allFields = append(allFields, m.Results...)

			for _, f := range allFields {
				extractUsedTypes(f.Type, imports, usedImports)
			}
		}
	}

	return usedImports
}

func collectImportsFromFile(file *ast.File, imports map[string]string) {
	authcommon.CollectImportsFromFile(file, imports)
}

func extractUsedTypes(expr ast.Expr, allImports, usedImports map[string]string) {
	authcommon.ExtractUsedTypes(expr, allImports, usedImports)
}

func genInterfaceWrapper(pkg *packages.Package, b *bytes.Buffer, iface authcommon.InterfaceInfo) {
	wrapName := "authorized" + iface.Name

	fmt.Fprintf(b, "type %s struct {\n\tnext %s\n\tconfig config.Config\n\ttracer trace.Tracer\n}\n\n", wrapName, iface.Name)

	// constructor that takes auth config
	fmt.Fprintf(b, "func Wrap%s(next %s, config config.Config) %s {\n", iface.Name, iface.Name, iface.Name)
	fmt.Fprintf(b, "\ttracer := otel.GetTracerProvider().Tracer(\"authwrap\")\n")
	fmt.Fprintf(b, "\treturn &%s{next: next, config: config, tracer: tracer}\n", wrapName)
	fmt.Fprintf(b, "}\n\n")

	fmt.Fprintf(b, "func (w *%s) GetUnderlying() any {\n", wrapName)
	fmt.Fprintf(b, "\treturn w.next\n")
	fmt.Fprintf(b, "}\n\n")

	for _, m := range iface.Methods {
		genMethod(pkg, b, wrapName, iface.Name, m)
	}
}

func genMethod(pkg *packages.Package, b *bytes.Buffer, wrapName, ifaceName string, m authcommon.MethodInfo) {
	// signature
	fmt.Fprintf(b, "func (w *%s) %s(", wrapName, m.Name)
	authcommon.WriteFieldList(b, m.Params)
	fmt.Fprintf(b, ")")
	authcommon.WriteResults(b, m.Results)
	fmt.Fprintf(b, " {\n")

	// enforce presence of ctx as first param if there are auth rules
	if len(m.AuthRules) > 0 && !m.HasContext {
		// compile-time-ish failure, generate a panic so it's obvious
		fmt.Fprintf(b, "\tpanic(\"%s.%s has @auth but does not take context.Context as first param\")\n", ifaceName, m.Name)
		writeZeroReturn(pkg, b, m.Results)
		fmt.Fprintf(b, "}\n\n")
		return
	}
	fmt.Fprintf(b, "\tctx, span := w.tracer.Start(ctx, \"%s\", trace.WithAttributes(\n", m.Name)
	for _, r := range m.AuthRules {
		// convert resource and action names to full protobuf enum constants
		resourceEnum := fmt.Sprintf("auth.Resource_%s", r.Resource)
		actionEnum := fmt.Sprintf("auth.Action_%s", r.Action)
		fmt.Fprintf(b, "\t\tattribute.Stringer(\"resource\", %s),\n", resourceEnum)
		fmt.Fprintf(b, "\t\tattribute.Stringer(\"action\", %s),\n", actionEnum)
	}
	fmt.Fprintf(b, "\t))\n")
	fmt.Fprintf(b, "\tdefer span.End()\n")

	// auth checks
	if len(m.AuthRules) > 0 {
		fmt.Fprintf(b, "\t// skip auth checks if auth is disabled\n")
		fmt.Fprintf(b, "\tif w.config.Auth.Enabled {\n")
		fmt.Fprintf(b, "\t\t// get principal from context\n")
		fmt.Fprintf(b, "\t\tprincipal, ok := authz.UserPrincipalFromContext(ctx)\n")
		fmt.Fprintf(b, "\t\tif !ok || principal == nil {\n")
		fmt.Fprintf(b, "\t\t\treturn %s\n", errorReturnForResults(pkg, m.Results))
		fmt.Fprintf(b, "\t\t}\n\n")

		fmt.Fprintf(b, "\t\tspan.SetAttributes(\n")
		fmt.Fprintf(b, "\t\t\tattribute.String(\"user.id\", principal.User.GetIdUUID().String()),\n")
		fmt.Fprintf(b, "\t\t\tattribute.String(\"user.username\", principal.User.Username),\n")
		fmt.Fprintf(b, "\t\t)\n\n")

		for _, r := range m.AuthRules {
			objExpr := strings.TrimSpace(r.ObjectID)
			objCode := "uuid.Nil"
			if objExpr != "" {
				objCode = objExpr
			}

			// convert resource and action names to full protobuf enum constants
			resourceEnum := fmt.Sprintf("auth.Resource_%s", r.Resource)
			actionEnum := fmt.Sprintf("auth.Action_%s", r.Action)

			fmt.Fprintf(b, "\t\tif err := authz.RequirePermission(ctx, %s, %s, %s); err != nil {\n",
				resourceEnum, actionEnum, objCode)
			fmt.Fprintf(b, "\t\tspan.RecordError(err)\n")
			fmt.Fprintf(b, "\t\t\t")
			writeErrorReturn(pkg, b, m.Results)
			fmt.Fprintf(b, "\t\t}\n")
		}
		fmt.Fprintf(b, "\t}\n\n")
	}

	// call original method
	if len(m.Results) == 0 {
		fmt.Fprintf(b, "\tw.next.%s(%s)\n", m.Name, authcommon.CallArgList(m.Params))
		fmt.Fprintf(b, "\treturn\n")
		fmt.Fprintf(b, "}\n\n")
		return
	}

	fmt.Fprintf(b, "\treturn w.next.%s(%s)\n", m.Name, authcommon.CallArgList(m.Params))
	fmt.Fprintf(b, "}\n\n")
}

// writeZeroReturn writes a zero return statement
func writeZeroReturn(pkg *packages.Package, b *bytes.Buffer, results []*ast.Field) {
	if len(results) == 0 {
		return
	}
	fmt.Fprintf(b, "\treturn")
	zeros := authcommon.ZeroExprs(pkg, results)
	if len(zeros) > 0 {
		fmt.Fprintf(b, " %s", strings.Join(zeros, ", "))
	}
	fmt.Fprintf(b, "\n")
}

// writeErrorReturn writes an error return statement
func writeErrorReturn(pkg *packages.Package, b *bytes.Buffer, results []*ast.Field) {
	if len(results) == 0 {
		fmt.Fprintf(b, "\t\treturn\n")
		return
	}

	if authcommon.LastIsError(results) {
		zeros := authcommon.ZeroExprs(pkg, results[:len(results)-1])
		if len(zeros) == 0 {
			fmt.Fprintf(b, "\t\treturn err\n")
			return
		}
		fmt.Fprintf(b, "\t\treturn %s, err\n", strings.Join(zeros, ", "))
		return
	}

	fmt.Fprintf(b, "\t\tpanic(err)\n")
}

// errorReturnForResults returns the appropriate error return expression
func errorReturnForResults(pkg *packages.Package, results []*ast.Field) string {
	if len(results) == 0 {
		return ""
	}

	if authcommon.LastIsError(results) {
		zeros := authcommon.ZeroExprs(pkg, results[:len(results)-1])
		if len(zeros) == 0 {
			return "authz.ErrUnauthenticated"
		}
		return fmt.Sprintf("%s, authz.ErrUnauthenticated", strings.Join(zeros, ", "))
	}

	return "panic(authz.ErrUnauthenticated)"
}
