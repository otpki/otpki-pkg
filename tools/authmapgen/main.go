package main

import (
	"flag"
	"fmt"
	"log"
	"path/filepath"
	"sort"
	"strings"

	"github.com/otpki/otpki-pkg/tools/authcommon"
	"github.com/samber/oops"
)

var (
	rootPath = flag.String("root", "./internal", "root path to search for packages with @auth annotations")
	verbose  = flag.Bool("v", false, "verbose output for debugging")
	output   = flag.String("output", "", "output file path (default: {root}/services/auth/authmeta/authmap.gen.go)")
)

func main() {
	flag.Parse()

	services, err := authcommon.DiscoverServices(*rootPath, *verbose)
	if err != nil {
		panic("Error discovering services: " + err.Error())
	}

	if len(services) == 0 {
		log.Println("No services with @auth annotations found")
		return
	}

	if *verbose {
		log.Printf("Found %d services with @auth annotations:\n", len(services))
		for _, svc := range services {
			log.Printf("  - %s\n", svc.PackagePath)
		}
	}

	// determine output path
	outputPath := *output
	if outputPath == "" {
		outputPath = filepath.Join(*rootPath, "services", "auth", "authmeta", "authmap.gen.go")
	}

	// generate a single consolidated auth map
	err = generateConsolidatedAuthMap(services, outputPath)
	if err != nil {
		panic("Error generating consolidated auth map: " + err.Error())
	}
}

func generateConsolidatedAuthMap(services []authcommon.ServiceInfo, outputPath string) error {
	if len(services) == 0 {
		log.Printf("Warning: No services with @auth found\n")
		return nil
	}

	code, err := generateConsolidatedAuthMapCode(services)
	if err != nil {
		return oops.Errorf("failed to generate consolidated auth map code: %w", err)
	}

	return authcommon.WriteGeneratedFile(outputPath, "consolidated auth map", code, *verbose)
}

func generateConsolidatedAuthMapCode(services []authcommon.ServiceInfo) ([]byte, error) {
	var b strings.Builder

	// header
	fmt.Fprintf(&b, "// Code generated by authmapgen. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// This file contains a consolidated map of all resources and their allowed actions\n")
	fmt.Fprintf(&b, "// across all services in the system.\n")
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "package authmeta\n\n")

	// imports
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\tauth \"github.com/otpki/otpki-protobuf/gen/otpki/common/auth/v1\"\n")
	fmt.Fprintf(&b, ")\n\n")

	// collect all resource-action pairs across all services
	resourceActions := make(map[string]map[string]bool) // resource -> set of actions

	for _, svc := range services {
		for _, iface := range svc.Interfaces {
			for _, method := range iface.Methods {
				for _, rule := range method.AuthRules {
					if resourceActions[rule.Resource] == nil {
						resourceActions[rule.Resource] = make(map[string]bool)
					}
					resourceActions[rule.Resource][rule.Action] = true
				}
			}
		}
	}

	// generate the main map
	fmt.Fprintf(&b, "// ResourceActions maps each resource to its allowed actions\n")
	fmt.Fprintf(&b, "// This map is generated from @auth annotations across all service interfaces\n")
	fmt.Fprintf(&b, "var ResourceActions = map[auth.Resource][]auth.Action{\n")

	// sort resources for stable output
	resources := make([]string, 0, len(resourceActions))
	for resource := range resourceActions {
		resources = append(resources, resource)
	}
	sort.Strings(resources)

	for _, resource := range resources {
		actions := resourceActions[resource]
		actionList := make([]string, 0, len(actions))
		for action := range actions {
			actionList = append(actionList, action)
		}
		sort.Strings(actionList)

		fmt.Fprintf(&b, "\tauth.Resource_%s: {\n", resource)
		for _, action := range actionList {
			fmt.Fprintf(&b, "\t\tauth.Action_%s,\n", action)
		}
		fmt.Fprintf(&b, "\t},\n")
	}

	fmt.Fprintf(&b, "}\n\n")

	// generate helper functions
	fmt.Fprintf(&b, "// GetAllowedActions returns the allowed actions for a given resource\n")
	fmt.Fprintf(&b, "func GetAllowedActions(resource auth.Resource) []auth.Action {\n")
	fmt.Fprintf(&b, "\tif actions, exists := ResourceActions[resource]; exists {\n")
	fmt.Fprintf(&b, "\t\treturn actions\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn nil\n")
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// IsActionAllowed checks if a specific action is allowed for a resource\n")
	fmt.Fprintf(&b, "func IsActionAllowed(resource auth.Resource, action auth.Action) bool {\n")
	fmt.Fprintf(&b, "\tallowedActions := ResourceActions[resource]\n")
	fmt.Fprintf(&b, "\tfor _, allowedAction := range allowedActions {\n")
	fmt.Fprintf(&b, "\t\tif allowedAction == action {\n")
	fmt.Fprintf(&b, "\t\t\treturn true\n")
	fmt.Fprintf(&b, "\t\t}\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\treturn false\n")
	fmt.Fprintf(&b, "}\n")

	return []byte(b.String()), nil
}
